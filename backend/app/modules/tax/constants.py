"""ثوابت ضريبة القيمة المضافة. أي رقم أو نص ثابت يُكتب هنا فقط.

النسب بنقاط الأساس (basis points) أعداداً صحيحة: 1400 = 14%، 500 = 5%. فلا float في الحساب أبداً.
"""

from enum import StrEnum

RATE_SCALE = 10_000  # 100% بنقاط الأساس
DEFAULT_RATE = 1400  # 14% (النسبة العامة في مصر)
MAX_RATE = RATE_SCALE  # 100%


class TaxType(StrEnum):
    """المعاملة الضريبية للصنف."""

    TAXABLE = "taxable"  # خاضع بنسبة tax_rate
    EXEMPT = "exempt"  # معفى
    ZERO = "zero"  # خاضع بنسبة صفر


class TaxMode(StrEnum):
    """طريقة حساب الفاتورة (لقطة على الفاتورة وقت البيع)."""

    OFF = "off"  # المحل غير مسجل: لا ضريبة (الافتراضي، سلوك النظام قبل الإضافة)
    INCLUSIVE = "inclusive"  # أسعار البيع شاملة الضريبة: الإجمالي لا يتغير والضريبة مستخلصة منه
    EXCLUSIVE = "exclusive"  # أسعار البيع قبل الضريبة: الضريبة تُضاف على الإجمالي
